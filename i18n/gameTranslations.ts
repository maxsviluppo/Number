export const translateGameText = (text: string, language: Language) => {
  if (!text.trim()) return text;
  const pairs = language === 'en'
    ? GAME_TRANSLATION_PAIRS
    : GAME_TRANSLATION_PAIRS.map(([it, en]) => [en, it] as [string, string]);

  let translated = text;
  [...pairs].sort((a, b) => b[0].length - a[0].length).forEach(([from, to]) => {
    translated = translated.replaceAll(from, to);
  });
  return translated;
};
